// Render a Plan into Klipper config files. No decisions here beyond formatting.
import { CfgFile, Section } from './cfg.ts';
import type { Plan, StepperPlan, FanPlan } from './plan.ts';
import { TOOLHEAD_MCU } from './plan.ts';
import type { Db, Rec } from './types.ts';
import { homingMacros, levelingMacros, preflightMacros, printMacros, tuningMacros } from './macros.ts';

export function emit(p: Plan, db: Db, dataRev: string): Record<string, string> {
  const b = p.build;
  const header = (what: string) => [
    `${what} - generated by klipper-configurator (data ${dataRev})`,
    `${p.printer.name} ${p.size.id} ${p.variant.name} · ${p.board.name} ${p.board.revisions.join('/')}` +
      (p.toolboard ? ` · ${p.toolboard.name} ${p.toolboard.revisions.join('/')}` : ''),
    'Regenerate instead of hand-editing where possible; SAVE_CONFIG values live in printer.cfg.',
  ];

  const files: Record<string, string> = {};
  const sensorless = b.homing.xy === 'sensorless';

  // ---------------------------------------------------------------- printer.cfg
  const eddy = p.probe?.kind === 'eddy_native';
  const beacon = p.probe?.kind === 'eddy_plugin';
  const probeHoming = b.homing.z === 'probe_virtual_endstop';
  const webUi = b.webUi ?? 'mainsail';
  const pc = new CfgFile([
    ...header('printer.cfg'),
    '',
    'Start here after wiring:',
    ...p.links.filter((l) => ['first power-on', 'printer'].includes(l.topic)).map((l) => `  ${l.title}: ${l.url}`),
  ]);
  if (webUi !== 'none') {
    pc.add(new Section(`include ${webUi}.cfg`, `${webUi === 'mainsail' ? 'Mainsail' : 'Fluidd'} client macros: PAUSE / RESUME / CANCEL_PRINT, virtual_sdcard`));
  }
  pc.add(new Section('include mainboard.cfg'));
  if (p.toolboard) pc.add(new Section('include toolhead.cfg'));
  if (eddy || beacon) pc.add(new Section('include probe.cfg'));
  if (sensorless) pc.add(new Section('include homing.cfg'));
  if (b.autotune) pc.add(new Section('include autotune.cfg'));
  for (const m of ['print', 'leveling', 'preflight', 'tuning']) pc.add(new Section(`include macros/${m}.cfg`));

  const d = p.printer.defaults;
  const pr = new Section('printer').set('kinematics', p.printer.kinematics);
  for (const [k, v] of Object.entries(d.printer)) pr.set(k, v as number);
  pc.add(pr);
  pc.add(new Section('idle_timeout').set('timeout', d.idle_timeout));
  pc.add(new Section('respond'));
  pc.add(new Section('exclude_object', 'needed for adaptive meshes and object cancelling'));
  if (webUi === 'none') {
    pc.add(new Section('virtual_sdcard').set('path', '~/printer_data/gcodes').set('on_error_gcode', 'CANCEL_PRINT'));
    pc.add(new Section('pause_resume'));
    pc.add(new Section('display_status'));
  }
  // force_move: sensorless homing macros and the first eddy calibration when homing with it
  // (Klipper Eddy_Probe.md) both need SET_KINEMATIC_POSITION.
  if (sensorless || (eddy && probeHoming)) {
    pc.add(new Section('force_move', sensorless ? 'used by homing.cfg' : 'first eddy calibration (Klipper Eddy_Probe.md)')
      .set('enable_force_move', true));
  }

  const [bedX, bedY] = p.size.bed_mm;
  const center = `${bedX / 2}, ${bedY / 2}`;
  // Beacon's own homing (home_xy_position in [beacon]) excludes [safe_z_home];
  // sensorless homing uses homing_override, which also excludes it.
  if (!sensorless && !(beacon && probeHoming)) {
    const xy = probeHoming ? [bedX / 2, bedY / 2] : b.homing.zSwitchXY ?? [bedX / 2, bedY / 2];
    pc.add(new Section('safe_z_home')
      .set('home_xy_position', `${xy[0]}, ${xy[1]}`, b.homing.z === 'nozzle_switch' ? 'nozzle switch position' : 'bed center')
      .set('speed', d.safe_z_home.speed)
      .set('z_hop', d.safe_z_home.z_hop)
      .set('z_hop_speed', 15, 'Klipper default')
      .set('move_to_previous', false));
  }
  if (p.printer.z_leveling === 'quad_gantry_level' && p.size.quad_gantry_level) {
    const q = p.size.quad_gantry_level;
    const s = new Section('quad_gantry_level', `${p.printer.name} ${p.size.id} (Voron reference geometry)`)
      .set('gantry_corners', q.gantry_corners.map((c: number[]) => c.join(', ')))
      .set('points', q.points.map((c: number[]) => c.join(', ')));
    for (const [k, v] of Object.entries(d.quad_gantry_level)) s.set(k, v as number);
    pc.add(s);
  }
  if (p.printer.z_leveling === 'z_tilt' && p.size.z_tilt) {
    const z = p.size.z_tilt;
    const s = new Section('z_tilt', `${p.printer.name} ${p.size.id} (Voron reference geometry)`)
      .set('z_positions', z.z_positions.map((c: number[]) => c.join(', ')))
      .set('points', z.points.map((c: number[]) => c.join(', ')));
    for (const [k, v] of Object.entries(d.z_tilt)) s.set(k, v as number);
    pc.add(s);
  }
  if (p.probe || p.bltouch) {
    // Mesh limits are probe coordinates: nozzle travel shifted by the probe offset, with a margin.
    const off = p.probe!.offset;
    const margin = eddy || beacon ? 15 : 30;
    const lo = (o: number) => Math.max(0, o) + margin;
    const hi = (size: number, o: number) => Math.min(size, size + o) - margin;
    const mesh = p.probe?.mesh ?? {};
    const scan = eddy || beacon;
    const bm = new Section('bed_mesh')
      .set('speed', mesh.speed ?? 300)
      .set('horizontal_move_z', mesh.horizontal_move_z ?? 10, scan ? 'scan height for eddy probes (vendor sample)' : undefined)
      .set('mesh_min', `${lo(off.x)}, ${lo(off.y)}`, `probe coordinates (offset ${off.x}, ${off.y}), ${margin} mm margin`)
      .set('mesh_max', `${hi(bedX, off.x)}, ${hi(bedY, off.y)}`)
      .set('probe_count', (mesh.probe_count ?? [5, 5]).join(', '))
      .set('algorithm', 'bicubic')
      .set('bicubic_tension', 0.2, 'Klipper default')
      .set('mesh_pps', '2, 2', 'Klipper default')
      .set('fade_start', 1.0)
      .set('fade_end', 10.0, 'Klipper recommends 10 when using fade; set 0 to disable')
      .set('split_delta_z', 0.025, 'Klipper default')
      .set('move_check_distance', 5.0, 'Klipper default')
      .set('adaptive_margin', 5, 'extra mm around the print area for BED_MESH_CALIBRATE ADAPTIVE=1');
    if (probeHoming) bm.set('zero_reference_position', center, 'Z=0 where Z is homed (bed center)');
    pc.add(bm);
  }
  if (p.accel) {
    pc.add(new Section('resonance_tester')
      .set('accel_chip', p.accel.chip)
      .set('probe_points', [`${bedX / 2}, ${bedY / 2}, 20`]));
  } else if (p.toolhead?.input_shaper_baseline) {
    const s = p.toolhead.input_shaper_baseline;
    pc.add(new Section('input_shaper', `baseline for ${p.toolhead.name} (${s.confidence} confidence) - measure to replace`)
      .set('shaper_type_x', s.x.type).set('shaper_freq_x', s.x.freq_hz)
      .set('shaper_type_y', s.y.type).set('shaper_freq_y', s.y.freq_hz));
  }
  files['printer.cfg'] = pc.render();

  // ------------------------------------------------------------ mainboard.cfg
  const mb = new CfgFile(header('mainboard.cfg'));
  mb.add(mcuSection('mcu', p.board, b.mainboard.connection, p.mcu.chip));
  mb.add(new Section('temperature_sensor mainboard').set('sensor_type', 'temperature_mcu'));
  const tb = p.toolboard ? new CfgFile(header('toolhead.cfg')) : undefined;
  if (tb) {
    const tconn = b.toolboard!.connection ?? (p.toolboard!.interfaces.includes('can') ? 'can' : 'usb');
    tb.add(mcuSection(`mcu ${TOOLHEAD_MCU}`, p.toolboard!, tconn, p.toolboard!.mcu.chip));
    tb.add(new Section('temperature_sensor toolhead').set('sensor_type', 'temperature_mcu').set('sensor_mcu', TOOLHEAD_MCU));
  }
  const fileFor = (board: 'mainboard' | 'toolboard') => (board === 'toolboard' ? tb! : mb);

  for (const s of p.steppers) {
    const f = fileFor(s.board);
    f.add(s.name === 'extruder' ? extruderSection(s) : stepperSection(s, p));
    f.add(tmcSection(s, p, db));
  }

  // [extruder] holds both the stepper and the hotend heater keys.
  function extruderSection(es: StepperPlan): Section {
    const sec = stepperSection(es, p);
    const hd = p.hotend;
    sec.set('nozzle_diameter', b.nozzleDiameter ?? 0.4).set('filament_diameter', 1.75)
      .set('heater_pin', p.hotendHeater.pin)
      .set('sensor_type', p.thermistor.hotend.sensor_type)
      .set('sensor_pin', p.hotendSensor.pin);
    if (p.hotendSensor.pullup !== 4700) sec.set('pullup_resistor', p.hotendSensor.pullup, 'board thermistor pull-up');
    const hdef = db.hotendDefaults;
    sec.set('min_temp', hdef.min_temp).set('max_temp', p.maxTemp)
      .set('max_power', hdef.max_power).set('min_extrude_temp', hdef.min_extrude_temp)
      .set('max_extrude_only_distance', 150, 'room for the 100 mm rotation_distance test')
      .set('control', 'pid', `seed values; run TUNE_PID_HOTEND (${hd.name})`)
      .set('pid_kp', hdef.pid_seed.pid_kp).set('pid_ki', hdef.pid_seed.pid_ki).set('pid_kd', hdef.pid_seed.pid_kd)
      .set('pressure_advance', p.paBaseline, `baseline (${p.extruder.name} + ${hd.flow_class}); run TUNE_PA`);
    return sec;
  }

  const bed = new Section('heater_bed')
    .set('heater_pin', p.bedHeater.pin, `${p.bedHeater.port}`)
    .set('sensor_type', p.thermistor.bed.sensor_type)
    .set('sensor_pin', p.bedSensor.pin, p.bedSensor.port);
  if (p.bedSensor.pullup !== 4700) bed.set('pullup_resistor', p.bedSensor.pullup, 'board thermistor pull-up');
  bed.set('max_power', b.bed?.maxPower ?? 0.6, 'SSR rating / (bed watts / mains volts), max 1.0')
    .set('min_temp', 0).set('max_temp', b.bed?.maxTemp ?? 120)
    .set('control', 'pid', 'seed values; run TUNE_PID_BED')
    .set('pid_kp', 58.437).set('pid_ki', 2.347).set('pid_kd', 363.769);
  mb.add(bed);

  if (p.chamberSensor && p.thermistor.chamber) {
    const c = new Section('temperature_sensor chamber')
      .set('sensor_type', p.thermistor.chamber.sensor_type).set('sensor_pin', p.chamberSensor.pin);
    if (p.chamberSensor.pullup && p.chamberSensor.pullup !== 4700) c.set('pullup_resistor', p.chamberSensor.pullup);
    fileFor(p.chamberSensor.board).add(c);
  }

  for (const f of p.fans) fileFor(f.board).add(fanSection(f));

  if (p.probe?.port) {
    const pr = p.probe;
    const s = new Section('probe', pr.name).set('pin', pr.port!.pin)
      .set('x_offset', pr.offset.x).set('y_offset', pr.offset.y).set('z_offset', 0, 'set by PROBE_CALIBRATE');
    const dflt = pr.defaults ?? { speed: 5.0, samples: 3, samples_result: 'median', sample_retract_dist: 2.0, samples_tolerance: 0.006, samples_tolerance_retries: 3 };
    for (const [k, v] of Object.entries(dflt)) if (!['x_offset', 'y_offset', 'z_offset'].includes(k)) s.set(k, v as number);
    if (pr.id === 'voron-tap') {
      s.set('activate_gcode', [
        '{% set PROBE_TEMP = 150 %}',
        '{% set MAX_TEMP = PROBE_TEMP + 5 %}',
        '{% set ACTUAL_TEMP = printer.extruder.temperature %}',
        '{% set TARGET_TEMP = printer.extruder.target %}',
        '{% if TARGET_TEMP > PROBE_TEMP %}',
        '    { action_respond_info(\'Extruder temperature target of %.1fC is too high, lowering to %.1fC\' % (TARGET_TEMP, PROBE_TEMP)) }',
        '    M109 S{ PROBE_TEMP }',
        '{% else %}',
        '    {% if ACTUAL_TEMP > MAX_TEMP %}',
        '        { action_respond_info(\'Extruder temperature %.1fC is still too high, waiting until below %.1fC\' % (ACTUAL_TEMP, MAX_TEMP)) }',
        '        TEMPERATURE_WAIT SENSOR=extruder MAXIMUM={ MAX_TEMP }',
        '    {% endif %}',
        '{% endif %}',
      ]);
    }
    fileFor(pr.port!.board).add(s);
  }
  if (p.bltouch) {
    fileFor(p.bltouch.board).add(new Section('bltouch')
      .set('sensor_pin', p.bltouch.sensor).set('control_pin', p.bltouch.control)
      .set('x_offset', p.probe!.offset.x).set('y_offset', p.probe!.offset.y).set('z_offset', 0));
  }
  if (p.accel) {
    const a = new Section(p.accel.chip).set('cs_pin', `${TOOLHEAD_MCU}:${p.accel.cs_pin}`);
    if (p.accel.spi_bus) a.set('spi_bus', p.accel.spi_bus);
    else {
      a.set('spi_software_sclk_pin', `${TOOLHEAD_MCU}:${p.accel.spi_software.sclk_pin}`)
        .set('spi_software_mosi_pin', `${TOOLHEAD_MCU}:${p.accel.spi_software.mosi_pin}`)
        .set('spi_software_miso_pin', `${TOOLHEAD_MCU}:${p.accel.spi_software.miso_pin}`);
    }
    tb!.add(a);
  }
  if (p.leds) {
    tb!.add(new Section('neopixel toolhead_leds').set('pin', p.leds.pin)
      .set('chain_count', p.leds.chain).set('color_order', p.leds.order)
      .set('initial_RED', 0.2).set('initial_GREEN', 0.2).set('initial_BLUE', 0.2).set('initial_WHITE', p.leds.order.length === 4 ? 0.2 : undefined));
  }

  files['mainboard.cfg'] = mb.render();
  if (eddy || beacon) files['probe.cfg'] = probeFile(p, header('probe.cfg'));
  if (tb) files['toolhead.cfg'] = tb.render();

  // ------------------------------------------------------------- autotune.cfg
  if (b.autotune) {
    const at = new CfgFile([...header('autotune.cfg'), 'Requires https://github.com/andrewmcgr/klipper_tmc_autotune installed on the host.']);
    for (const s of p.steppers) {
      if (!s.motor) { at.add(`# ${s.name}: motor not in the autotune database - add a [motor_constants] section to tune it`); continue; }
      const sec = new Section(`autotune_tmc ${s.name}`).set('motor', s.motor.autotune_name);
      if (s.driver.hv) sec.set('voltage', 48, 'HV driver supply; set to your actual HV voltage');
      if (sensorless && (s.name === 'stepper_x' || s.name === 'stepper_y')) {
        const t = db.homing.xy_methods.sensorless.starting_thresholds[s.driver.chip];
        if (s.driver.chip === 'tmc2209' || s.driver.chip === 'tmc2226') sec.set('sg4_thrs', t?.driver_SGTHRS ?? 80, 'sensorless threshold: tune it');
        else sec.set('sgt', t?.driver_SGT ?? 1, 'sensorless threshold: tune it');
      }
      if (s.driver.chip === 'tmc2240' && s.board === 'toolboard') {
        at.add(sec.render() + '\n# overvoltage_vth: <measured toolhead voltage + 0.8>   # klipper_tmc_autotune README, SB2240');
        continue;
      }
      at.add(sec);
    }
    files['autotune.cfg'] = at.render();
  }

  if (sensorless) files['homing.cfg'] = homingMacros(p, header('homing.cfg'));
  files['macros/print.cfg'] = printMacros(p, header('macros/print.cfg'));
  files['macros/leveling.cfg'] = levelingMacros(p, header('macros/leveling.cfg'));
  files['macros/preflight.cfg'] = preflightMacros(p, header('macros/preflight.cfg'));
  files['macros/tuning.cfg'] = tuningMacros(p, header('macros/tuning.cfg'));
  return files;
}

function mcuSection(name: string, board: Rec, conn: string, chip: string): Section {
  const s = new Section(name, `${board.name}`);
  if (conn === 'usb') {
    s.set('serial', `/dev/serial/by-id/usb-Klipper_${chip}_REPLACE_ME-if00`, 'ls /dev/serial/by-id/*');
    s.set('restart_method', 'command');
  } else {
    // Placeholders must differ: Klipper rejects duplicate canbus_uuid values.
    const who = name === 'mcu' ? 'MAINBOARD' : name.split(' ')[1].toUpperCase();
    s.set('canbus_uuid', `REPLACE_WITH_${who}_UUID`, '~/klippy-env/bin/python ~/klipper/scripts/canbus_query.py can0');
  }
  return s;
}

function stepperSection(s: StepperPlan, p: Plan): Section {
  const d = p.printer.defaults;
  const sec = new Section(s.name, `${s.board === 'toolboard' ? p.toolboard!.name : s.slot}${s.position ? ` · ${s.role} ${s.position}` : ` · ${s.role}`}`)
    .set('step_pin', s.step).set('dir_pin', s.dir, 'direction verified in PREFLIGHT_MOTORS').set('enable_pin', s.enable)
    .set('microsteps', s.microsteps).set('rotation_distance', s.rotationDistance)
    .set('gear_ratio', s.gearRatio).set('full_steps_per_rotation', s.fullSteps);
  if (s.name === 'stepper_x' || s.name === 'stepper_y') {
    const axis = s.name === 'stepper_x' ? 'x' : 'y';
    const xy = d.stepper_xy;
    const max = p.size.position_max[axis];
    const sensorless = s.endstop === 'virtual';
    sec.set('endstop_pin', sensorless ? `${s.driver.section}_${s.name}:virtual_endstop` : (s.endstop as any).pin,
      sensorless ? 'sensorless' : (s.endstop as any).port)
      .set('position_min', xy.position_min)
      .set('position_endstop', xy.endstop_at_max ? max : 0).set('position_max', max)
      .set('homing_speed', sensorless ? (p.build.autotune ? Math.max(50, s.rotationDistance + 10) : s.rotationDistance / 2) : xy.homing_speed,
        sensorless ? (p.build.autotune ? 'autotune: must exceed rotation_distance' : 'Klipper: rotation_distance / 2') : undefined)
      .set('homing_retract_dist', sensorless ? 0 : xy.homing_retract_dist)
      .set('homing_positive_dir', xy.homing_positive_dir);
  } else if (s.name === 'stepper_z') {
    const z = d.stepper_z;
    if (s.endstop === 'probe') {
      sec.set('endstop_pin', 'probe:z_virtual_endstop');
    } else {
      sec.set('endstop_pin', (s.endstop as any).pin, (s.endstop as any).port)
        .set('position_endstop', z.position_endstop, 'Z_ENDSTOP_CALIBRATE stores the real value');
    }
    sec.set('position_max', p.size.position_max.z).set('position_min', z.position_min)
      .set('homing_speed', z.homing_speed).set('second_homing_speed', z.second_homing_speed)
      .set('homing_retract_dist', z.homing_retract_dist);
  }
  return sec;
}

function tmcSection(s: StepperPlan, p: Plan, db: Db): Section {
  const d = s.driver;
  const sec = new Section(`${d.section} ${s.name}`, d.onboard ? `onboard ${d.chip}` : `${d.moduleId}, ${d.iface.toUpperCase()}`);
  for (const [k, v] of Object.entries(d.pins)) sec.set(k, v);
  if (d.rref) sec.set('rref', d.rref);
  else if (d.sense) sec.set('sense_resistor', d.sense);
  sec.set('run_current', s.runCurrent, s.currentNote);
  const auto = !!p.build.autotune;
  sec.set('interpolate', auto ? true : p.printer.defaults.tmc.interpolate, auto ? 'klipper_tmc_autotune recommends interpolation' : undefined);
  if (!auto) sec.set('stealthchop_threshold', p.printer.defaults.tmc.stealthchop_threshold);
  if (s.endstop === 'virtual' && d.diag) {
    sec.set(d.diag.key, d.diag.pin, 'sensorless homing; DIAG jumper on for stepsticks');
    if (!auto) {
      const chip = db.drivers.chips[d.chip];
      const start = db.homing.xy_methods.sensorless.starting_thresholds[d.chip] ?? {};
      const key = chip.sensorless.threshold_key;
      sec.set(key, start[key], 'starting point: tune it');
    }
  }
  return sec;
}

function fanSection(f: FanPlan): Section {
  const s = new Section(f.section, `${f.board} ${f.port}`).set('pin', f.pin);
  if (f.tach) s.set('tachometer_pin', f.tach);
  for (const [k, v] of Object.entries(f.defaults)) s.set(k, v as any);
  return s;
}

// Eddy current probes: their own MCU (or Beacon's module) and calibration notes.
function probeFile(p: Plan, header: string[]): string {
  const pr = p.probe!;
  const docs = (pr.docs ?? []).map((d: Rec) => `${d.title}: ${d.url}`);
  const f = new CfgFile([...header, '', 'Calibrate before the first print (see macros/tuning.cfg TUNE_EDDY / vendor docs):', ...docs.map((d: string) => `  ${d}`)]);
  if (pr.kind === 'eddy_plugin') {
    f.add(`# Requires the Beacon Klipper module: ${pr.plugin.repo} (${pr.plugin.install}).`);
    const s = new Section('beacon').set('serial', `/dev/serial/by-id/${pr.serial_hint}`, 'ls /dev/serial/by-id/*')
      .set('x_offset', pr.offset.x).set('y_offset', pr.offset.y);
    if (p.build.homing.z === 'probe_virtual_endstop') {
      const [bx, by] = p.size.bed_mm;
      s.set('home_xy_position', `${bx / 2}, ${by / 2}`, 'Beacon homes Z here; replaces [safe_z_home]')
        .set('home_z_hop', 5).set('home_z_hop_speed', 30);
    }
    f.add(s);
    return f.render();
  }
  const m = pr.mcu;
  const conn = pr.connection ?? 'usb';
  const mcu = new Section(`mcu ${m.name}`, pr.name);
  if (conn === 'usb') mcu.set('serial', `/dev/serial/by-id/${m.serial_hint}`, 'ls /dev/serial/by-id/*').set('restart_method', 'command');
  else mcu.set('canbus_uuid', `REPLACE_WITH_${m.name.toUpperCase()}_UUID`, '~/klippy-env/bin/python ~/klipper/scripts/canbus_query.py can0');
  f.add(mcu);
  f.add(new Section(`temperature_sensor ${m.name}_mcu`).set('sensor_type', 'temperature_mcu').set('sensor_mcu', m.name));
  if (pr.extra_sections) f.add(pr.extra_sections.trimEnd());
  const e = pr.eddy;
  const name = e.section_name ?? m.name;
  const s = new Section(`probe_eddy_current ${name}`).set('sensor_type', 'ldc1612');
  if (e.frequency) s.set('frequency', e.frequency);
  if (e.i2c_address) s.set('i2c_address', e.i2c_address);
  s.set('i2c_mcu', e.i2c_mcu).set('i2c_bus', e.i2c_bus)
    .set('descend_z', 0.5, 'Klipper Eddy_Probe.md recommendation')
    .set('x_offset', pr.offset.x).set('y_offset', pr.offset.y)
    .set('speed', 5).set('lift_speed', 10)
    .set('samples', 3).set('samples_result', 'median').set('sample_retract_dist', 2.0)
    .set('samples_tolerance', 0.01).set('samples_tolerance_retries', 3);
  f.add(s);
  if (pr.temperature_probe) {
    const t = pr.temperature_probe;
    const ts = new Section(`temperature_probe ${name}`, 'coil temperature for drift compensation')
      .set('sensor_type', t.sensor_type).set('sensor_pin', `${m.name}:${t.sensor_pin}`);
    if (t.horizontal_move_z) ts.set('horizontal_move_z', t.horizontal_move_z);
    f.add(ts);
  }
  return f.render();
}
