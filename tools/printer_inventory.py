#!/usr/bin/env python3
"""Write docs/PRINTERS.md: every printer the configurator supports, and the ones it doesn't yet.

Usage: python3 -I tools/printer_inventory.py [KLIPPER_DIR]
With KLIPPER_DIR, Klipper's reference configs that are not in the data are listed with the reason.
"""
import glob
import json
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
printers = [yaml.safe_load(open(f)) for f in sorted(glob.glob(os.path.join(ROOT, "data", "printers", "*.yaml")))]
boards = {yaml.safe_load(open(f))["id"]: yaml.safe_load(open(f)) for f in glob.glob(os.path.join(ROOT, "data", "mainboards", "*.yaml"))}

lines = ["# Supported printers", "",
         "Generated by `tools/printer_inventory.py` from the data; do not edit by hand.", "",
         "\"Needs review\" means the pins come from a single source (usually Klipper's own reference config for the printer):",
         "check them against your printer before powering on.", "",
         "| Printer | Maker | Stock board | Pin data | Source |", "|---|---|---|---|---|"]
for p in sorted(printers, key=lambda p: (str(p["manufacturer"]).lower(), p["name"].lower())):
    stock = (p.get("stock") or {}).get("mainboards") or []
    b = boards.get(stock[0]) if stock else None
    board = f"{b['name']} {'/'.join(map(str, b.get('revisions', [])))}".replace(" stock", "") if b else "your choice (kit)"
    # Reviewed only when the printer record and its stock board both are (SV05: reviewed board, single-source printer).
    status = "Reviewed" if p.get("status") == "reviewed" and (b is None or b.get("status") == "reviewed") else "Needs review"
    src = p.get("imported_from") or (p.get("sources") or [{}])[0]
    link = f"[{src.get('path', src.get('url', ''))}]({src['repo']}/blob/master/{src['path']})" if src.get("repo") and src.get("path") else src.get("url", "")
    lines.append(f"| {p['name']} | {p['manufacturer']} | {board} | {status} | {link} |")
lines += ["", f"{len(printers)} printers.", ""]

if len(sys.argv) > 1:
    names = json.load(open(os.path.join(ROOT, "tools", "klipper_printer_names.json")))
    imported = {(p.get("imported_from") or {}).get("path") for p in printers}
    covered_by_hand = {"creality-ender3-v2-2020", "creality-ender3-v2-neo-2022", "creality-ender3pro-2020", "creality-ender3-s1-2021",
                       "creality-ender5pro-2020", "sovol-sv06-2022", "elegoo-neptune3-pro-2023"}
    rows = []
    for f in sorted(glob.glob(os.path.join(sys.argv[1], "config", "printer-*.cfg"))):
        n = os.path.basename(f)[8:-4]
        if f"config/printer-{n}.cfg" in imported or n in covered_by_hand:
            continue
        t = open(f, errors="replace").read()
        why = names.get(n, {}).get("skip") or "not imported yet"
        rows.append(f"| printer-{n}.cfg | {why} |")
    if rows:
        lines += ["# Not supported yet", "", "Klipper reference configs that are not in the configurator yet, and why.", "",
                  "| Klipper config | Why |", "|---|---|", *rows, ""]

vendor = json.load(open(os.path.join(ROOT, "tools", "vendor_klipper_status.json")))
lines += ["# Printers running their maker's own Klipper", "",
          "These ship with a modified Klipper from the maker. They are not in the configurator yet; the reason is given for each.", "",
          "| Printers | Why not yet |", "|---|---|"]
lines += [f"| {k} | {v} |" for k, v in vendor.items() if not k.startswith("_")]
lines.append("")

open(os.path.join(ROOT, "docs", "PRINTERS.md"), "w").write("\n".join(lines))
print(f"wrote docs/PRINTERS.md ({len(printers)} printers)")
